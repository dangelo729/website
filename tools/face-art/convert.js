// makes js/face-art.js and js/hand-art.js from cicada_site's bitmaps:
//
//   node tools/face-art/convert.js <cicada_site dir>
//
// each of cicada's assets/bitmaps/{eyes,nose,mouf,hand1}.js is an es module
// holding one animation, its frames packed 1 bit a pixel, msb first, the bits
// running on from row to row (bit y * width + x, rows not padded to a byte).
// the export line is cut, the rest run as a function body, and every frame is
// written out as rows of '.' and '#', the way font.js keeps its glyphs.
// before anything is written each new file is run back and every pixel of
// every frame checked against cicada's own getPixel. hand2.js is hand1.js
// mirrored, so it is not carried: js/cursor.js can mirror the one hand itself.

const fs = require('fs');
const path = require('path');

const JS = path.join(__dirname, '..', '..', 'js');
// each file one global, each of its parts one of cicada's animations
const FILES = [
  {
    out: 'face-art.js', name: 'FACE_ART',
    head: [
      '// the face\'s bitmaps, every frame as rows of \'.\' and \'#\' like font.js.',
      '// generated by tools/face-art/convert.js from cicada_site\'s',
      '// assets/bitmaps/{eyes,nose,mouf}.js: run that again, do not edit here.',
    ],
    parts: [
      { key: 'eyes', src: 'eyes', note: '0 shut .. 6 open' },
      { key: 'nose', src: 'nose', note: '0 at rest .. 3 sniffed' },
      { key: 'mouf', src: 'mouf', note: '0 shut .. 9 open' },
    ],
  },
  {
    out: 'hand-art.js', name: 'HAND_ART',
    head: [
      '// the hand\'s bitmap, every frame as rows of \'.\' and \'#\' like font.js.',
      '// generated by tools/face-art/convert.js from cicada_site\'s',
      '// assets/bitmaps/hand1.js: run that again, do not edit here. its thumb',
      '// is on the left; hand2.js is the same hand mirrored, so it is not kept.',
    ],
    parts: [
      { key: 'hand', src: 'hand1', note: '0 open, fingers up .. 13 a fist' },
    ],
  },
];

function fail(msg) {
  console.error('convert: ' + msg);
  process.exit(1);
}

// the animation object out of one of cicada's module files
function load(dir, name) {
  const file = path.join(dir, 'assets', 'bitmaps', name + '.js');
  let src;
  try {
    src = fs.readFileSync(file, 'utf8');
  } catch (e) {
    fail('cannot read ' + file);
  }
  const m = src.match(/^\s*export\s+default\s+([A-Za-z_$][\w$]*)\s*;?\s*$/m);
  if (!m) fail(file + ': no export default line');
  const body = src.replace(m[0], '') + '\nreturn ' + m[1] + ';';
  const anim = new Function(body)();
  if (!anim || !Array.isArray(anim.frames) || anim.frames.length === 0) fail(file + ': no frames');
  if (anim.frameCount !== anim.frames.length) fail(file + ': frameCount ' + anim.frameCount + ' but ' + anim.frames.length + ' frames');
  return anim;
}

// one frame as row strings, read straight from the packed bits
function rows(frame) {
  const out = [];
  for (let y = 0; y < frame.height; y++) {
    let row = '';
    for (let x = 0; x < frame.width; x++) {
      const bit = y * frame.width + x;
      row += (frame.data[bit >> 3] >> (7 - (bit & 7))) & 1 ? '#' : '.';
    }
    out.push(row);
  }
  return out;
}

// one file's text, in font.js's layout, and how many pixels of it were
// checked against getPixel on the way back
function build(dir, file) {
  const anims = {};
  const art = {};
  for (const { key, src } of file.parts) {
    const anim = load(dir, src);
    const w = anim.frames[0].width, h = anim.frames[0].height;
    for (const f of anim.frames) {
      if (f.width !== w || f.height !== h) fail(key + ': frames differ in size');
      if (f.data.length < Math.ceil(w * h / 8)) fail(key + ': ' + f.name + ' is short of bits');
    }
    anims[key] = anim;
    art[key] = { w, h, frames: anim.frames.map(rows) };
  }

  let text = '';
  for (const line of file.head) text += line + '\n';
  text += 'const ' + file.name + ' = {\n';
  for (const { key, note } of file.parts) {
    const a = art[key];
    text += '  ' + key + ': { // ' + a.frames.length + ' frames, ' + note + '\n';
    text += '    w: ' + a.w + ',\n';
    text += '    h: ' + a.h + ',\n';
    text += '    frames: [\n';
    a.frames.forEach((f, i) => {
      text += '      [ // ' + i + '\n';
      for (const r of f) text += '        "' + r + '",\n';
      text += '      ],\n';
    });
    text += '    ],\n';
    text += '  },\n';
  }
  text += '};\n';

  // the round trip: what will be on disk, run back, against cicada's getPixel
  const back = new Function(text + '\nreturn ' + file.name + ';')();
  let pixels = 0;
  for (const { key } of file.parts) {
    const anim = anims[key], a = back[key];
    if (a.w !== anim.frames[0].width || a.h !== anim.frames[0].height) fail(key + ': size lost');
    if (a.frames.length !== anim.frames.length) fail(key + ': frames lost');
    anim.frames.forEach((f, i) => {
      const r = a.frames[i];
      if (r.length !== f.height) fail(key + ' ' + i + ': ' + r.length + ' rows, want ' + f.height);
      for (let y = 0; y < f.height; y++) {
        if (r[y].length !== f.width) fail(key + ' ' + i + ' row ' + y + ': ' + r[y].length + ' wide, want ' + f.width);
        for (let x = 0; x < f.width; x++) {
          const want = f.getPixel(x, y);
          const got = r[y][x] === '#' ? 1 : r[y][x] === '.' ? 0 : -1;
          if (got !== want) fail(key + ' ' + i + ' (' + x + ', ' + y + '): ' + got + ', getPixel says ' + want);
          pixels++;
        }
      }
    });
  }
  return { text, art, pixels };
}

const dir = process.argv[2];
if (!dir) fail('usage: node tools/face-art/convert.js <cicada_site dir>');

// every file built and checked before any is written
const built = FILES.map((file) => ({ file, ...build(dir, file) }));
for (const { file, text, art, pixels } of built) {
  const out = path.join(JS, file.out);
  fs.writeFileSync(out, text);
  console.log('convert: wrote ' + path.relative(process.cwd(), out) + ': ' +
    file.parts.map(({ key }) => key + ' ' + art[key].w + 'x' + art[key].h + 'x' + art[key].frames.length).join(', ') +
    '; ' + pixels + ' pixels match getPixel');
}
