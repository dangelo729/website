// makes js/face-art.js from cicada_site's face bitmaps:
//
//   node tools/face-art/convert.js <cicada_site dir>
//
// each of cicada's assets/bitmaps/{eyes,nose,mouf}.js is an es module holding
// one animation, its frames packed 1 bit a pixel, msb first, the bits running
// on from row to row (bit y * width + x, rows not padded to a byte). the
// export line is cut, the rest run as a function body, and every frame is
// written out as rows of '.' and '#', the way font.js keeps its glyphs.
// before anything is written the new file is run back and every pixel of
// every frame checked against cicada's own getPixel.

const fs = require('fs');
const path = require('path');

const PARTS = ['eyes', 'nose', 'mouf'];
const OUT = path.join(__dirname, '..', '..', 'js', 'face-art.js');

function fail(msg) {
  console.error('convert: ' + msg);
  process.exit(1);
}

// the animation object out of one of cicada's module files
function load(dir, part) {
  const file = path.join(dir, 'assets', 'bitmaps', part + '.js');
  let src;
  try {
    src = fs.readFileSync(file, 'utf8');
  } catch (e) {
    fail('cannot read ' + file);
  }
  const m = src.match(/^\s*export\s+default\s+([A-Za-z_$][\w$]*)\s*;?\s*$/m);
  if (!m) fail(file + ': no export default line');
  const body = src.replace(m[0], '') + '\nreturn ' + m[1] + ';';
  const anim = new Function(body)();
  if (!anim || !Array.isArray(anim.frames) || anim.frames.length === 0) fail(file + ': no frames');
  if (anim.frameCount !== anim.frames.length) fail(file + ': frameCount ' + anim.frameCount + ' but ' + anim.frames.length + ' frames');
  return anim;
}

// one frame as row strings, read straight from the packed bits
function rows(frame) {
  const out = [];
  for (let y = 0; y < frame.height; y++) {
    let row = '';
    for (let x = 0; x < frame.width; x++) {
      const bit = y * frame.width + x;
      row += (frame.data[bit >> 3] >> (7 - (bit & 7))) & 1 ? '#' : '.';
    }
    out.push(row);
  }
  return out;
}

const dir = process.argv[2];
if (!dir) fail('usage: node tools/face-art/convert.js <cicada_site dir>');

const anims = {};
const art = {};
for (const part of PARTS) {
  const anim = load(dir, part);
  const w = anim.frames[0].width, h = anim.frames[0].height;
  for (const f of anim.frames) {
    if (f.width !== w || f.height !== h) fail(part + ': frames differ in size');
    if (f.data.length < Math.ceil(w * h / 8)) fail(part + ': ' + f.name + ' is short of bits');
  }
  anims[part] = anim;
  art[part] = { w, h, frames: anim.frames.map(rows) };
}

// the file, in font.js's layout
const NOTES = {
  eyes: '0 shut .. 6 open',
  nose: '0 at rest .. 3 sniffed',
  mouf: '0 shut .. 9 open',
};
let text = '';
text += '// the face\'s bitmaps, every frame as rows of \'.\' and \'#\' like font.js.\n';
text += '// generated by tools/face-art/convert.js from cicada_site\'s\n';
text += '// assets/bitmaps/{eyes,nose,mouf}.js: run that again, do not edit here.\n';
text += 'const FACE_ART = {\n';
for (const part of PARTS) {
  const a = art[part];
  text += '  ' + part + ': { // ' + a.frames.length + ' frames, ' + NOTES[part] + '\n';
  text += '    w: ' + a.w + ',\n';
  text += '    h: ' + a.h + ',\n';
  text += '    frames: [\n';
  a.frames.forEach((f, i) => {
    text += '      [ // ' + i + '\n';
    for (const r of f) text += '        "' + r + '",\n';
    text += '      ],\n';
  });
  text += '    ],\n';
  text += '  },\n';
}
text += '};\n';

// the round trip: what will be on disk, run back, against cicada's getPixel
const back = new Function(text + '\nreturn FACE_ART;')();
let pixels = 0;
for (const part of PARTS) {
  const anim = anims[part], a = back[part];
  if (a.w !== anim.frames[0].width || a.h !== anim.frames[0].height) fail(part + ': size lost');
  if (a.frames.length !== anim.frames.length) fail(part + ': frames lost');
  anim.frames.forEach((f, i) => {
    const r = a.frames[i];
    if (r.length !== f.height) fail(part + ' ' + i + ': ' + r.length + ' rows, want ' + f.height);
    for (let y = 0; y < f.height; y++) {
      if (r[y].length !== f.width) fail(part + ' ' + i + ' row ' + y + ': ' + r[y].length + ' wide, want ' + f.width);
      for (let x = 0; x < f.width; x++) {
        const want = f.getPixel(x, y);
        const got = r[y][x] === '#' ? 1 : r[y][x] === '.' ? 0 : -1;
        if (got !== want) fail(part + ' ' + i + ' (' + x + ', ' + y + '): ' + got + ', getPixel says ' + want);
        pixels++;
      }
    }
  });
}

fs.writeFileSync(OUT, text);
console.log('convert: wrote ' + path.relative(process.cwd(), OUT) + ': ' +
  PARTS.map((p) => p + ' ' + art[p].w + 'x' + art[p].h + 'x' + art[p].frames.length).join(', ') +
  '; ' + pixels + ' pixels match getPixel');
